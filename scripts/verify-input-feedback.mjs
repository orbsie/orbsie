#!/usr/bin/env node

/**
 * Measure the first real editor feedback after a prompt submission.
 *
 * This is a deterministic browser check. It uses the test-only fixture
 * transport, observes the trusted form submission before React handles it,
 * and reports DOM feedback plus the next animation-frame observation. The
 * timings are observations, not INP or pixel visibility measurements.
 */
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { chromium, expect } from "@playwright/test";
import { installFixtureGeneration } from "./fixture-generation.mjs";

const TEST_URL = process.env.TEST_URL;
if (!TEST_URL)
  throw Error("TEST_URL must be set to the intended local editor origin.");

const EVIDENCE_DIR =
  process.env.ORBSIE_INPUT_FEEDBACK_EVIDENCE_DIR ??
  "docs/evidence/input-feedback";
const APP_SOURCE_COMMIT = process.env.ORBSIE_APP_SOURCE_COMMIT ?? "unverified";
const INITIAL_PROMPT =
  "Make a sunny little island game where I collect five glowing crystals, bounce across three moving platforms, and reach a portal. Add friendly trees and a pond.";
const WAIT_TIMEOUT = 45000;
const VIEWPORT = { width: 1440, height: 1000 };

function sourceCommit() {
  try {
    return execFileSync("git", ["rev-parse", "HEAD"], {
      encoding: "utf8",
    }).trim();
  } catch {
    return "unavailable";
  }
}

const report = {
  status: "running",
  mode: "deterministic-fixture-browser",
  scope:
    "Actual editor input feedback timing with fixture generation; no provider calls, pixel visibility, or INP claim.",
  url: TEST_URL,
  appSourceCommit: APP_SOURCE_COMMIT,
  repositoryCommit: sourceCommit(),
  fixtureTransport: true,
  viewport: VIEWPORT,
  fixtureRequestCount: 0,
  blockedExternalHttpRequests: [],
  fixtureFontStylesheets: [],
  pageErrors: [],
  consoleErrors: [],
  requestFailures: [],
  checks: {},
};

const testOrigin = new URL(TEST_URL).origin;
await mkdir(EVIDENCE_DIR, { recursive: true });

let browser;
let context;
let page;
try {
  browser = await chromium.launch({
    headless: true,
    args: [
      "--no-sandbox",
      "--use-gl=angle",
      "--use-angle=swiftshader",
      "--enable-unsafe-swiftshader",
    ],
  });
  context = await browser.newContext({
    viewport: VIEWPORT,
    reducedMotion: "reduce",
  });

  // This instrumentation only observes the real submit event generated by
  // Playwright below. The capture listener runs before React's form handler.
  await context.addInitScript(() => {
    const state = {
      submitEvents: [],
      domSignals: {},
      domFeedback: null,
      nextAnimationFrame: null,
    };
    window.__orbsieInputFeedback = state;

    const visible = (element) => {
      if (!element) return false;
      for (let current = element; current; current = current.parentElement) {
        const style = getComputedStyle(current);
        if (
          style.display === "none" ||
          style.visibility === "hidden" ||
          Number(style.opacity) === 0
        )
          return false;
      }
      const box = element.getBoundingClientRect();
      return (
        box.width > 0 &&
        box.height > 0 &&
        box.bottom > 0 &&
        box.right > 0 &&
        box.top < innerHeight &&
        box.left < innerWidth
      );
    };

    const feedbackConditions = (prompt) => {
      const app = document.querySelector(".app.is-workspace");
      const userMessage = [...document.querySelectorAll(".message.user")].some(
        (element) => element.textContent?.includes(prompt) && visible(element),
      );
      const buildingMessage = document.querySelector(".building-message");
      return {
        workspace: Boolean(app),
        userMessage,
        building: visible(buildingMessage),
      };
    };

    const observeFeedback = () => {
      const submit = state.submitEvents.at(-1);
      if (!submit) return;
      const conditions = feedbackConditions(submit.prompt);
      const now = performance.now();
      if (conditions.workspace && state.domSignals.workspaceAt === undefined)
        state.domSignals.workspaceAt = now;
      if (
        conditions.userMessage &&
        state.domSignals.userMessageAt === undefined
      )
        state.domSignals.userMessageAt = now;
      if (conditions.building && state.domSignals.buildingAt === undefined)
        state.domSignals.buildingAt = now;
      if (
        !state.domFeedback &&
        conditions.workspace &&
        conditions.userMessage &&
        conditions.building
      ) {
        state.domFeedback = {
          observedAt: now,
          conditions,
        };
        requestAnimationFrame(() => {
          const frameAt = performance.now();
          state.nextAnimationFrame = {
            observedAt: frameAt,
            latencyMs: frameAt - submit.observedAt,
            feedbackStillVisible: Object.values(
              feedbackConditions(submit.prompt),
            ).every(Boolean),
          };
        });
      }
    };

    document.addEventListener(
      "submit",
      (event) => {
        const form = event.target;
        if (!(form instanceof HTMLFormElement) || !form.matches(".prompt-form"))
          return;
        const textarea = form.querySelector("#prompt");
        const prompt =
          textarea instanceof HTMLTextAreaElement ? textarea.value : "";
        const observedAt = performance.now();
        state.submitEvents.push({
          prompt,
          observedAt,
          trusted: event.isTrusted,
        });
        queueMicrotask(observeFeedback);
      },
      true,
    );

    const attachObserver = () => {
      if (!document.documentElement || state.observerAttached) return;
      state.observerAttached = true;
      new MutationObserver(observeFeedback).observe(document.documentElement, {
        subtree: true,
        childList: true,
        attributes: true,
        characterData: true,
      });
      observeFeedback();
    };
    attachObserver();
    document.addEventListener("DOMContentLoaded", attachObserver, {
      once: true,
    });
  });

  // Keep the deterministic run on the editor origin. The one known stylesheet
  // is fulfilled locally so the document uses its declared fallback fonts.
  await context.route("**/*", async (route) => {
    const requestUrl = new URL(route.request().url());
    if (
      requestUrl.origin === "https://fonts.googleapis.com" &&
      requestUrl.pathname === "/css2"
    ) {
      report.fixtureFontStylesheets.push(requestUrl.href);
      await route.fulfill({ contentType: "text/css", body: "" });
      return;
    }
    if (
      (requestUrl.protocol === "http:" || requestUrl.protocol === "https:") &&
      requestUrl.origin !== testOrigin
    ) {
      report.blockedExternalHttpRequests.push({
        method: route.request().method(),
        url: route.request().url(),
      });
      await route.abort();
      return;
    }
    await route.fallback();
  });
  await installFixtureGeneration(context);

  page = await context.newPage();
  page.setDefaultTimeout(15000);
  page.setDefaultNavigationTimeout(20000);
  page.on("pageerror", (error) => report.pageErrors.push(error.message));
  page.on("console", (message) => {
    if (message.type() === "error") report.consoleErrors.push(message.text());
  });
  page.on("requestfailed", (request) => {
    report.requestFailures.push({
      method: request.method(),
      url: request.url(),
      failure: request.failure()?.errorText ?? "unknown",
    });
  });
  page.on("request", (request) => {
    if (new URL(request.url()).pathname === "/api/generate")
      report.fixtureRequestCount += 1;
  });

  await page.goto(TEST_URL, { waitUntil: "domcontentloaded" });
  await expect(page.locator("canvas")).toBeVisible();
  report.browser = await page.evaluate(() => {
    const canvas = document.querySelector("canvas");
    const gl =
      canvas?.getContext("webgl2") ?? canvas?.getContext("webgl") ?? null;
    let webgl = { vendor: null, renderer: null };
    if (gl) {
      const debug = gl.getExtension("WEBGL_debug_renderer_info");
      webgl = {
        vendor: debug
          ? gl.getParameter(debug.UNMASKED_VENDOR_WEBGL)
          : gl.getParameter(gl.VENDOR),
        renderer: debug
          ? gl.getParameter(debug.UNMASKED_RENDERER_WEBGL)
          : gl.getParameter(gl.RENDERER),
      };
    }
    return {
      userAgent: navigator.userAgent,
      platform: navigator.platform,
      language: navigator.language,
      hardwareConcurrency: navigator.hardwareConcurrency,
      devicePixelRatio: window.devicePixelRatio,
      viewport: {
        width: window.innerWidth,
        height: window.innerHeight,
      },
      webgl,
    };
  });
  report.browser.engine = "chromium";
  report.browser.version = browser.version();

  await page.getByPlaceholder("What experience to build?").fill(INITIAL_PROMPT);
  await page.getByRole("button", { name: "Create", exact: true }).click();
  await page.waitForFunction(
    () => window.__orbsieInputFeedback?.submitEvents?.length === 1,
    undefined,
    { timeout: 5000 },
  );
  await page.waitForFunction(
    () => Boolean(window.__orbsieInputFeedback?.nextAnimationFrame),
    undefined,
    { timeout: WAIT_TIMEOUT },
  );

  const measurement = await page.evaluate(() => {
    const state = window.__orbsieInputFeedback;
    const submit = state.submitEvents.at(-1);
    return {
      submit,
      domSignals: state.domSignals,
      domFeedback: state.domFeedback,
      nextAnimationFrame: state.nextAnimationFrame,
    };
  });
  assert.equal(measurement.submit?.prompt, INITIAL_PROMPT);
  assert.equal(measurement.submit?.trusted, true);
  assert.equal(measurement.nextAnimationFrame?.feedbackStillVisible, true);
  assert.ok(measurement.domFeedback, "DOM feedback was observed");
  const domFeedbackLatencyMs =
    measurement.domFeedback.observedAt - measurement.submit.observedAt;
  assert.ok(Number.isFinite(domFeedbackLatencyMs) && domFeedbackLatencyMs >= 0);
  assert.ok(
    Number.isFinite(measurement.nextAnimationFrame.latencyMs) &&
      measurement.nextAnimationFrame.latencyMs >= domFeedbackLatencyMs,
  );
  report.inputFeedback = {
    submittedPrompt: measurement.submit.prompt,
    submitCapturedAtPerformanceMs: measurement.submit.observedAt,
    domSignals: measurement.domSignals,
    domFeedbackObservedAtPerformanceMs: measurement.domFeedback.observedAt,
    domFeedbackLatencyMs,
    domFeedbackWithin100ms: domFeedbackLatencyMs <= 100,
    nextAnimationFrame: measurement.nextAnimationFrame,
    nextAnimationFrameLatencyMs:
      measurement.nextAnimationFrame?.latencyMs ?? null,
    nextAnimationFrameWithin100ms:
      measurement.nextAnimationFrame?.latencyMs <= 100,
    note: "DOM and animation-frame observations do not certify pixels, paint timing, or INP.",
  };
  report.checks.submitCapturedInCapturePhase = true;
  report.checks.workspaceUserMessageAndBuildingObserved = true;

  await expect(
    page.getByText("Your island is alive!", { exact: false }),
  ).toBeVisible({ timeout: WAIT_TIMEOUT });
  await expect(page.locator(".building-message")).toHaveCount(0, {
    timeout: WAIT_TIMEOUT,
  });
  await page.getByRole("button", { name: "Show objects", exact: true }).click();
  await expect(page.locator(".object-list button")).toHaveCount(14, {
    timeout: WAIT_TIMEOUT,
  });
  report.fixtureEntityCount = 14;
  report.checks.fixtureGenerationCompleted = true;
  assert.equal(report.fixtureRequestCount, 1);
  report.checks.oneFixtureGenerationRequest = true;
  assert.deepEqual(report.blockedExternalHttpRequests, []);
  assert.deepEqual(report.pageErrors, []);
  assert.deepEqual(report.consoleErrors, []);
  report.status = "passed";

  await page.getByRole("button", { name: "Show objects", exact: true }).click();
  await page.screenshot({ path: `${EVIDENCE_DIR}/final.png` });
  report.screenshot = "final.png";
} catch (error) {
  report.status = "failed";
  report.error = error instanceof Error ? error.message : String(error);
  process.exitCode = 1;
} finally {
  report.finishedAt = new Date().toISOString();
  await writeFile(
    `${EVIDENCE_DIR}/report.json`,
    JSON.stringify(report, null, 2) + "\n",
  );
  await context?.close().catch(() => undefined);
  await browser?.close().catch(() => undefined);
  console.log(JSON.stringify(report, null, 2));
}
